#!/bin/sh
# update-broad-profile.sh: regenerate nono-broad-profile.json (the
# "bulkhead-broad" nono profile) from IANA's list of top-level domains.
# Run it by hand now and then; it only reads a public file.
#
# The profile allows GET and HEAD to every host under every TLD, which
# is how we say "the whole web, read-only": nono 0.82 refuses even GET
# when "*" has endpoint rules, but accepts "*.<tld>" with them. See
# agent-network-plan.md ("Broad by default").
#
# Usage: ./update-broad-profile.sh [TLD-LIST-FILE]
# With no file, it fetches IANA's current list.
set -eu

cd "$(dirname "$0")"
out=nono-broad-profile.json
new=",$out.new"

if [ -n "${1:-}" ]; then
  list=$(cat "$1")
else
  list=$(curl -fsS https://data.iana.org/TLD/tlds-alpha-by-domain.txt)
fi

# IANA's file is one uppercase TLD per line after a "#" header line.
# Check its shape, so a broken download can't silently empty the list.
# Skip internationalized TLDs ("xn--..."): nono 0.82 refuses to start
# with some of them (e.g., "*.xn--4dbrk0ce": "invalid international
# domain name"), and they rarely matter for development work.
tlds=$(printf '%s\n' "$list" | grep -v '^#' | tr '[:upper:]' '[:lower:]' | grep -v '^xn--')
if printf '%s\n' "$tlds" | grep -qv '^[a-z0-9-]*$' ||
  [ "$(printf '%s\n' "$tlds" | wc -l)" -lt 1000 ]; then
  echo "update-broad-profile.sh: that doesn't look like IANA's TLD list." >&2
  exit 1
fi

# One entry per line, so diffs show exactly which TLDs changed.
{
  cat <<'EOF'
{
  "meta": {
    "name": "bulkhead-broad",
    "description": "GET and HEAD to every host under every IANA TLD; generated by update-broad-profile.sh"
  },
  "network": {
    "allow_domain": [
EOF
  printf '%s\n' "$tlds" |
    sed 's/.*/      {"domain": "*.&", "endpoints": [{"method": "GET", "path": "\/**"}, {"method": "HEAD", "path": "\/**"}]},/' |
    sed '$s/,$//'
  cat <<'EOF'
    ]
  }
}
EOF
} > "$new"
jq -e '.network.allow_domain | length > 1000' "$new" > /dev/null
mv "$new" "$out"
echo "Wrote $out ($(printf '%s\n' "$tlds" | wc -l) TLDs)."
